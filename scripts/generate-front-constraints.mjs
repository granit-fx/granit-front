const MAX_REF_DEPTH = 10;

function resolveRef(ref, schemas) {
  return schemas[ref.replace('#/components/schemas/', '')];
}

function mergeAllOf(schema, schemas, depth) {
  const properties = {};
  const required = new Set();

  for (const r of schema.required ?? []) required.add(r);
  Object.assign(properties, schema.properties ?? {});

  if (schema.allOf && depth < MAX_REF_DEPTH) {
    for (const entry of schema.allOf) {
      if (entry.$ref) {
        const refSchema = resolveRef(entry.$ref, schemas);
        if (!refSchema) continue;
        const merged = mergeAllOf(refSchema, schemas, depth + 1);
        Object.assign(properties, merged.properties);
        for (const r of merged.required) required.add(r);
        continue;
      }
      for (const r of entry.required ?? []) required.add(r);
      Object.assign(properties, entry.properties ?? {});
    }
  }

  return { properties, required };
}

// Mirrors buildFieldConstraint — order matches @granit/validation for stable diffs.
function buildFieldConstraint(prop, isRequired) {
  const c = {};
  if (isRequired) c.required = true;
  if (prop.maxLength !== undefined) c.maxLength = prop.maxLength;
  if (prop.minLength !== undefined) c.minLength = prop.minLength;
  if (prop.pattern !== undefined) c.pattern = prop.pattern;
  if (prop.format !== undefined) c.format = prop.format;
  if (prop.minimum !== undefined) c.minimum = prop.minimum;
  if (prop.maximum !== undefined) c.maximum = prop.maximum;
  if (prop.exclusiveMinimum !== undefined) c.exclusiveMinimum = prop.exclusiveMinimum;
  if (prop.exclusiveMaximum !== undefined) c.exclusiveMaximum = prop.exclusiveMaximum;
  if (prop['x-granit-validator'] !== undefined) c.granitValidator = prop['x-granit-validator'];
  if (prop['x-granit-pattern-hint'] !== undefined) c.patternHint = prop['x-granit-pattern-hint'];
  return c;
}

function extractConstraints(spec, schemaPattern) {
  const schemas = spec.components?.schemas ?? {};
  const result = {};
  for (const name of Object.keys(schemas).filter((n) => schemaPattern.test(n))) {
    const { properties, required } = mergeAllOf(schemas[name], schemas, 0);
    const fields = {};
    for (const [fieldName, prop] of Object.entries(properties)) {
      fields[fieldName] = buildFieldConstraint(prop, required.has(fieldName));
    }
    if (Object.keys(fields).length > 0) result[name] = fields;
  }
  return result;
}

function render(exportName, specFile, constraints) {
  const body = JSON.stringify(constraints, null, 2);
  return `// GENERATED by scripts/generate-front-constraints.mjs — DO NOT EDIT.
// Source: contracts/openapi/${specFile}
// Validation constraints derived from the OpenAPI contract (the single source of
// truth). Consumed via createConstraintsResolver from @granit/react-validation.
// Regenerated on pre-commit when the spec or the generator changes.

import type { SchemaConstraints } from '@granit/validation';

export const ${exportName} = ${body} satisfies Record<string, SchemaConstraints>;
`;
}

let changed = 0;
for (const target of TARGETS) {
  const specPath = join(ROOT, 'contracts/openapi', target.spec);
  const outPath = join(ROOT, 'packages/@granit', target.pkg, 'src/constraints.ts');
  if (!existsSync(specPath)) {
    console.error(`[constraints] spec not found: ${specPath}`);
    process.exitCode = 1;
    continue;
  }
  const spec = JSON.parse(readFileSync(specPath, 'utf8'));
  const constraints = extractConstraints(spec, target.schemaPattern);
  const next = render(target.exportName, target.spec, constraints);
  const prev = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (prev !== next) {
    writeFileSync(outPath, next);
    changed += 1;
    console.log(`[constraints] wrote ${outPath}`);
  }
}

if (changed === 0) console.log('[constraints] up to date');
