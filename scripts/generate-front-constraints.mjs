#!/usr/bin/env node
// Generates per-package validation-constraint constants from the authoritative
// OpenAPI contracts in `contracts/openapi/*.json`.
//
// WHY: DTOs are TYPES (compile-time, erased at runtime) so they are hand-mirrored
// from the contracts. Validation constraints are DATA (maxLength, pattern,
// required, …) already machine-readable in the same spec — so they are DERIVED,
// never hand-copied. This keeps the spec the single source of truth and avoids a
// third drifting copy (spec + .NET FluentValidation + hand-written client rules).
//
// The extraction logic mirrors `@granit/validation` `extractConstraints` (kept
// self-contained so the pre-commit hook needs no built dist). Output is consumed
// via `createConstraintsResolver` from `@granit/react-validation`.
//
// Regenerated by .husky/pre-commit. NEVER edit the generated files by hand.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Modules that derive client constraints from their contract. Add an entry when
// a core package starts exporting constraints for its forms.
