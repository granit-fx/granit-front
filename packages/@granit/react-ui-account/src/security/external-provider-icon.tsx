interface ExternalProviderIconProps {
  readonly provider: string;
  readonly className?: string;
}

/**
 * Branded icon for a provider scheme name (case-insensitive). Falls back to a
 * generic key glyph for unknown / custom OIDC schemes so any backend-configured
 * provider still renders.
 */
export function ExternalProviderIcon({ provider, className }: ExternalProviderIconProps) {
  const path = BRAND_PATHS[provider.toLowerCase()];
  if (!path) {
    return <KeyRound data-slot="external-provider-icon" className={className} aria-hidden="true" />;
  }
  return (
    <svg
      data-slot="external-provider-icon"
      viewBox="0 0 24 24"
      fill="currentColor"
      className={className}
      aria-hidden="true"
    >
      <path d={path} />
    </svg>
  );
}
